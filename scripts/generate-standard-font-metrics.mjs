// Generates src-tauri/src/engine/standard_fonts.rs from the AFM metrics that
// pdf-lib already bundles. The native engine needs exact advance widths for
// non-embedded standard fonts, which carry no /Widths array.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { Font, FontNames, Encodings } = require("@pdf-lib/standard-fonts");

const latin = [
  FontNames.Courier,
  FontNames.CourierBold,
  FontNames.CourierOblique,
  FontNames.CourierBoldOblique,
  FontNames.Helvetica,
  FontNames.HelveticaBold,
  FontNames.HelveticaOblique,
  FontNames.HelveticaBoldOblique,
  FontNames.TimesRoman,
  FontNames.TimesRomanBold,
  FontNames.TimesRomanItalic,
  FontNames.TimesRomanBoldItalic,
];

function entries(font, encoding) {
  const pairs = new Map();
  for (const codePoint of encoding.supportedCodePoints) {
    const { code, name } = encoding.encodeUnicodeCodePoint(codePoint);
    const width = font.getWidthOfGlyph(name);
    if (typeof width === "number") pairs.set(codePoint, { code, width });
  }
  return pairs;
}

function block(fontName, builtin) {
  const font = Font.load(fontName);
  const encoding = builtin ? Encodings[fontName] : Encodings.WinAnsi;
  const pairs = entries(font, encoding);
  const unicode = builtin
    ? []
    : [...pairs.entries()]
        .sort((a, b) => a[0] - b[0])
        .map(([codePoint, value]) => `(${codePoint}, ${value.width})`);
  const codes = builtin
    ? [...pairs.values()]
        .sort((a, b) => a.code - b.code)
        .map((value) => `(${value.code}, ${value.width})`)
    : [];
  const space = font.getWidthOfGlyph("space");
  return `    StandardFont {
        name: "${fontName}",
        ascent: ${font.Ascender ?? font.FontBBox[3]},
        descent: ${font.Descender ?? font.FontBBox[1]},
        missing_width: ${typeof space === "number" ? space : 500},
        unicode_widths: &[${unicode.join(", ")}],
        builtin_code_widths: &[${codes.join(", ")}],
    },`;
}

const body = [
  "// @generated by scripts/generate-standard-font-metrics.mjs from @pdf-lib/standard-fonts.",
  "// Do not edit manually; run `node scripts/generate-standard-font-metrics.mjs`.",
  "",
  "pub struct StandardFont {",
  "    pub name: &'static str,",
  "    pub ascent: i32,",
  "    pub descent: i32,",
  "    pub missing_width: u32,",
  "    /// Sorted (Unicode scalar, advance width) pairs for WinAnsi-encodable glyphs.",
  "    pub unicode_widths: &'static [(u32, u32)],",
  "    /// Sorted (built-in code, advance width) pairs for Symbol and ZapfDingbats.",
  "    pub builtin_code_widths: &'static [(u8, u32)],",
  "}",
  "",
  "pub static STANDARD_FONTS: &[StandardFont] = &[",
  ...latin.map((name) => block(name, false)),
  block(FontNames.Symbol, true),
  block(FontNames.ZapfDingbats, true),
  "];",
  "",
].join("\n");

const target = path.resolve("src-tauri/src/engine/standard_fonts.rs");
await writeFile(target, body);
console.log(`Wrote ${target}`);
